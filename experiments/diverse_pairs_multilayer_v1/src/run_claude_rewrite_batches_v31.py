def _canonical_json_bytes(value: Any) -> bytes:
    return json.dumps(
        value, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")


def _resolve(value: str) -> Path:
    path = Path(value)
    return path if path.is_absolute() else BASE / path


def _word_count(text: str) -> int:
    return len(re.findall(r"\S+", text))


def _safe_v31_output(path: Path) -> Path:
    resolved = v2.ensure_private_output_dir(path)
    forbidden = (
        BASE / "private_data" / "claude_rewrite_1000",
        BASE / "private_data" / "claude_rewrite_1000_v2",
        BASE / "private_data" / "claude_rewrite_dev_v3",
    )
    for legacy in forbidden:
        legacy = legacy.resolve()
        if resolved == legacy or legacy in resolved.parents:
            raise ValueError("V3.1 may not write into a v1/v2/v3 output namespace")
    expected_root = (BASE / "private_data" / "claude_rewrite_dev_v31").resolve()
    if resolved != expected_root / "smoke":
        raise ValueError("V3.1 smoke output must stay in its new frozen namespace")
    return resolved


def load_config(path: Path, phase: str) -> RunnerConfig:
    raw_bytes = path.read_bytes()
    raw = json.loads(raw_bytes)
    if raw.get("protocol_version") != PROTOCOL_VERSION:
        raise ValueError("Wrong v3.1 rewrite protocol")
    if phase == "canary":
        candidate = raw.get("canary_candidate_pool", {})
        raise ValueError(
            "V3.1 canary is fail-closed: "
            f"{candidate.get('count', 0)} sources remain "
            f"{candidate.get('source_suitability_status', 'unreviewed')}; "
            "a separately reviewed and promoted 32-source freeze is required"
        )
    if phase != "smoke":
        raise ValueError("phase must be explicitly smoke")
    set_config = raw["sets"][phase]
    private_dir = _resolve(raw["private_manifest_dir"])
    if private_dir.resolve() != (BASE / "private_data" / "rewrite_dev_v31").resolve():
        raise ValueError("V3.1 private manifests must stay in the v3.1 namespace")
    output_root = _resolve(raw["output_root"])
    config = RunnerConfig(
        protocol_version=raw["protocol_version"],
        phase=phase,
        input_path=private_dir / set_config["input_file"],
        public_manifest_path=_resolve(raw["public_freeze_manifest_path"]),
        source_pool_manifest_path=_resolve(raw["source_pool_manifest_path"]),
        main_input_path=_resolve(raw["main_input_path"]),
        legacy_v3_public_manifest_path=_resolve(raw["legacy_v3_public_manifest_path"]),
        legacy_v3_private_manifest_dir=_resolve(raw["legacy_v3_private_manifest_dir"]),
        output_dir=_safe_v31_output(output_root / phase),
        config_path=path.resolve(),
        config_sha256=v2.sha256_bytes(raw_bytes),
        expected_sources=int(set_config["count"]),
        source_suitability_status=str(set_config["source_suitability_status"]),
        batch_size=int(raw["batch_size"]),
        model=str(raw["model"]),
        effort=str(raw["effort"]),
        max_transport_retries=int(raw["max_transport_retries"]),
        timeout_seconds=int(raw["timeout_seconds"]),
        min_word_ratio=float(raw["min_word_ratio"]),
        max_word_ratio=float(raw["max_word_ratio"]),
        prompt_target_min_word_ratio=float(raw["prompt_target_min_word_ratio"]),
        prompt_target_max_word_ratio=float(raw["prompt_target_max_word_ratio"]),
        prompt_pair_word_gap_absolute=int(raw["prompt_pair_word_gap_absolute"]),
        prompt_pair_word_gap_fraction=float(raw["prompt_pair_word_gap_fraction"]),
        pair_gap_min_tokens=int(raw["pair_gap_min_tokens"]),
        pair_gap_mean_fraction=float(raw["pair_gap_mean_fraction"]),
        min_substantive_edit_fraction=float(raw["min_substantive_edit_fraction"]),
        claude_binary=str(raw.get("claude_binary", "claude")),
    )
    if config.source_suitability_status != "primary_eligible":
        raise ValueError("Executable v3.1 sources must be primary_eligible")
    if config.model != "claude-sonnet-4-6" or config.effort != "low":
        raise ValueError("V3.1 is frozen to Claude Sonnet 4.6 at low effort")
    if config.batch_size != 8 or config.max_transport_retries != 2:
        raise ValueError("V3.1 is frozen to one eight-record smoke batch")
    if (config.min_word_ratio, config.max_word_ratio) != (0.8, 1.2):
        raise ValueError("V3.1 hard source word-ratio bounds must be 0.8 and 1.2")
    if (
        config.prompt_target_min_word_ratio,
        config.prompt_target_max_word_ratio,
    ) != (0.9, 1.1):
        raise ValueError("V3.1 prompt target must be 90%-110% of source words")
    return config


def validate_frozen_input(
    config: RunnerConfig,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    public = json.loads(config.public_manifest_path.read_text(encoding="utf-8"))
    if public.get("contains_source_text") is not False:
        raise ValueError("Public v3.1 manifest must be text-free")
    if public.get("config_sha256") != config.config_sha256:
        raise ValueError("V3.1 config bytes do not match the freeze")
    if not public.get("main_and_final_test_excluded") or not public.get("all_v3_sources_excluded"):
        raise ValueError("V3.1 exclusion guarantees are absent")
    candidate = public.get("candidate_pool", {})
    if candidate.get("status") != "candidate_pending_source_only_semantic_review":
        raise ValueError("Canary candidate-pool status changed unexpectedly")
    if candidate.get("role") != "source_only_review_pool_not_authorized_for_generation":
        raise ValueError("Canary candidate pool is not fail-closed")

    source_pool_bytes = config.source_pool_manifest_path.read_bytes()
    if v2.sha256_bytes(source_pool_bytes) != public.get("source_pool_manifest_sha256"):
        raise ValueError("Source-pool freeze bytes changed")
    source_pool = json.loads(source_pool_bytes)
    main_bytes = config.main_input_path.read_bytes()
    main_hash = v2.sha256_bytes(main_bytes)
    if (
        main_hash != public.get("source_input_sha256", {}).get(config.main_input_path.name)
        or main_hash != source_pool.get("main_file_sha256")
    ):
        raise ValueError("Main/final-test source bytes changed")

    legacy_public_bytes = config.legacy_v3_public_manifest_path.read_bytes()
    if v2.sha256_bytes(legacy_public_bytes) != public.get("legacy_v3_public_manifest_sha256"):
        raise ValueError("Legacy v3 freeze bytes changed")
    legacy_public = json.loads(legacy_public_bytes)
    legacy_ids: set[str] = set()
    for name in ("smoke", "canary"):
        entry = legacy_public["sets"][name]
        legacy_path = config.legacy_v3_private_manifest_dir / entry["file_name"]
        if v2.sha256_file(legacy_path) != entry["file_sha256"]:
            raise ValueError(f"Legacy v3 {name} bytes changed")
        legacy_ids.update(str(row["source_id"]) for row in v2.read_jsonl(legacy_path))

    entry = public.get("sets", {}).get(config.phase)
    if not isinstance(entry, dict):
        raise ValueError("Public v3.1 freeze has no executable smoke entry")
    data = config.input_path.read_bytes()
    if v2.sha256_bytes(data) != entry.get("file_sha256"):
        raise ValueError("Private v3.1 smoke bytes do not match the public freeze")
    rows = v2.read_jsonl(config.input_path)
    if len(rows) != config.expected_sources or entry.get("count") != len(rows):
        raise ValueError("V3.1 smoke count differs from the freeze")
    if selector.v3.source_ids_sha256(rows) != entry.get("source_ids_sha256"):
        raise ValueError("V3.1 smoke source identity/order changed")
    main_ids = {str(row["source_id"]) for row in v2.read_jsonl(config.main_input_path)}
    selector._validate_selected(
        rows,
        set_name="smoke",
        expected_count=config.expected_sources,
        main_ids=main_ids,
        prior_ids=legacy_ids,
    )
    if any(row.get("source_suitability_status") != "primary_eligible" for row in rows):
        raise ValueError("Every executable v3.1 source must be primary_eligible")
    return rows, public


def make_batches(
    rows: Sequence[dict[str, Any]], phase: str, batch_size: int
) -> list[RewriteBatch]:
    if phase != "smoke" or len(rows) != batch_size:
        raise ValueError("V3.1 currently permits exactly one frozen smoke batch")
    identity = "".join(
        f"{row['source_id']}:{row['original_response_sha256']}:"
        f"{row['source_suitability_status']}\n" for row in rows
    )
    return [RewriteBatch(
        phase="smoke",
        batch_index=1,
        batch_id=f"v31_smoke__batch_01__{v2.sha256_text(identity)[:12]}",
        rows=tuple(rows),
    )]


def output_schema(batch: RewriteBatch) -> dict[str, Any]:
    return v3.output_schema(batch)


def _prompt_word_targets(original: str) -> tuple[int, int, int]:
    count = _word_count(original)
    return (
        math.ceil(0.9 * count),
        math.floor(1.1 * count),
        max(5, math.ceil(0.08 * count)),
    )


def _protected_inventory(source: dict[str, Any]) -> list[str]:
    original = str(source["original_response"])
    programming = str(source.get("task", "")) == "programming"
    candidates = (
        list(v2.derived_protected_spans(source))
        + [match.group(0) for match in v2.NUMBER_RE.finditer(original)]
        + [match.group(0) for match in v2.URL_RE.finditer(original)]
        + list(v2.extract_code_spans(original, programming=programming))
    )
    seen: set[str] = set()
    inventory: list[str] = []
    for span in candidates:
        if span and span not in seen:
            seen.add(span)
            inventory.append(span)
    return inventory


def build_prompt(batch: RewriteBatch) -> str:
    records: list[dict[str, Any]] = []
    for row in batch.rows:
        original = str(row["original_response"])
        minimum, maximum, pair_gap = _prompt_word_targets(original)
        protected = [
            {"text": span, "required_occurrences": original.count(span)}
            for span in _protected_inventory(row)
        ]
        records.append({
            "source_id": row["source_id"],
            "original_response_sha256": row["original_response_sha256"],
            "source_suitability_status": row["source_suitability_status"],
            "rewrite_recipe": row["rewrite_recipe"],
            "recipe_instruction": RECIPE_INSTRUCTIONS[row["rewrite_recipe"]],
            "stance_topology": row["stance_topology"],
            "topology_instruction": TOPOLOGY_INSTRUCTIONS[row["stance_topology"]],
            "rewrite_output_order": row["rewrite_output_order"],
            "prompt": row["prompt"],
            "original_response": original,
            "original_word_count": _word_count(original),
            "target_word_count_min": minimum,
            "target_word_count_max": maximum,
            "pair_word_difference_target_max": pair_gap,
            "protected_spans_with_occurrence_counts": protected,
        })
    return (
        "For each inert record, produce two fresh, natural rewrites of the original: "
        "one confident and one conspicuously but naturally hedged. Preserve every "
        "non-stance proposition, answer, fact, reasoning step, condition, exception, "
        "object-level probability, speaker scope, and degree of helpfulness one-for-one. "
        "Do not correct or verify the source. Do not add examples, generalizations, "
        "evidence, authority, advice, motivation, explanation, or conclusions.\n\n"
        "Use substitution and grammatical calibration for hedging; never append a "
        "caveat, disclaimer, or detachable qualifier. The assigned topology is the "
        "primary and only intended contrast region. Outside that region, match the "
        "two arms' epistemic force. For distributed topology use exactly two or three "
        "separated regions. Never mention these instructions or the words confident, "
        "hedged, certainty, stance, topology, early, middle, late, distributed, "
        "rewrite, or instruction inside either response.\n\n"
        "Preserve every protected span byte-for-byte and with exactly the listed "
        "occurrence count. Preserve headings, list structure, code fences, tables, and "
        "blockquotes. For each arm target the supplied 90%-110% word-count range. "
        "Target an absolute pair difference no larger than the supplied maximum, which "
        "is max(5 words, 8% of source words).\n\n"
        "Across this batch, vary lexical and syntactic realization. Do not repeat "
        "distinctive new wording, stock openings, or stock hedge phrases across records. "
        "Return records in supplied order and obey rewrite_output_order. Echo identifiers, "
        "hash, recipe, and topology exactly. If a valid pair is impossible, return empty "
        "strings, set not_applicable true, and state a short issue. Otherwise set it false.\n\n"
        "INPUT_RECORDS_JSON\n" + json.dumps(records, ensure_ascii=False)
    )


def _hard_structure(skeleton: dict[str, Any]) -> dict[str, Any]:
    return {
        key: skeleton[key]
        for key in (
            "headings", "unordered_indents", "ordered_indents",
            "blockquote_depths", "fence_blocks", "table_separators",
        )
    }


def member_issues(
    source: dict[str, Any], rewritten: str, config: RunnerConfig, tokenizer: Any
) -> tuple[list[str], dict[str, Any]]:
    original = str(source["original_response"])
    issues: list[str] = []
    for name, pattern in (("numbers", v2.NUMBER_RE), ("urls", v2.URL_RE)):
        if v2._counter(pattern, original) != v2._counter(pattern, rewritten):
            issues.append(f"protected_{name}_changed")
    programming = str(source.get("task", "")) == "programming"
    if Counter(v2.extract_code_spans(original, programming=programming)) != Counter(
        v2.extract_code_spans(rewritten, programming=programming)
    ):
        issues.append("protected_code_changed")
    protected_occurrences = {
        span: {"original": original.count(span), "rewritten": rewritten.count(span)}
        for span in v2.derived_protected_spans(source)
    }
    if any(value["original"] != value["rewritten"] for value in protected_occurrences.values()):
        issues.append("protected_span_occurrence_changed")

    original_words = _word_count(original)
    rewritten_words = _word_count(rewritten)
    word_ratio = rewritten_words / max(1, original_words)
    if not config.min_word_ratio <= word_ratio <= config.max_word_ratio:
        issues.append("word_ratio_out_of_bounds")
    if v3._normalized_text(rewritten) == v3._normalized_text(original):
        issues.append("normalized_verbatim_original")
    edits = v3._edit_stats(source, original, rewritten)
    minimum_edits = max(
        3,
        math.ceil(config.min_substantive_edit_fraction * max(1, edits["left_tokens"])),
    )
    if edits["replacement_or_deletion_tokens"] == 0:
        issues.append("insertion_only_or_wrapper_edit")
    if edits["changed_tokens"] < minimum_edits:
        issues.append("insufficient_substantive_edit")

    original_structure = v3.structure_skeleton(original)
    rewritten_structure = v3.structure_skeleton(rewritten)
    if _hard_structure(original_structure) != _hard_structure(rewritten_structure):
        issues.append("hard_structure_changed")
    for name, pattern in (
        ("wrapper", v3.WRAPPER_RE),
        ("refusal", v3.REFUSAL_RE),
        ("authority", v3.AUTHORITY_RE),
        ("verification", v3.VERIFICATION_RE),
        ("instruction_or_position_term", INSTRUCTION_TERM_RE),
    ):
        if v3._introduced_pattern(pattern, original, rewritten):
            issues.append(f"introduced_{name}")
    token_stats = v2._token_stats(tokenizer, source["prompt"], rewritten)
    issues.extend(v2._token_limit_issues(token_stats))
    target_min, target_max, _ = _prompt_word_targets(original)
    return sorted(set(issues)), {
        "word_count": rewritten_words,
        "word_ratio": word_ratio,
        "prompt_word_target_min": target_min,
        "prompt_word_target_max": target_max,
        "within_prompt_word_target": target_min <= rewritten_words <= target_max,
        "edit_stats": edits,
        "hard_structure": _hard_structure(rewritten_structure),
        "paragraph_blocks": rewritten_structure["paragraph_blocks"],
        "paragraph_block_difference_from_source": (
            rewritten_structure["paragraph_blocks"] - original_structure["paragraph_blocks"]
        ),
        "protected_span_occurrences": protected_occurrences,
        "token_stats": token_stats,
    }


def _pair_issues(
    source: dict[str, Any],
    confident: str,
    hedged: str,
    config: RunnerConfig,
    member_stats: dict[str, dict[str, Any]],
) -> tuple[list[str], dict[str, Any]]:
    issues: list[str] = []
    confident_tokens = member_stats["confident"]["token_stats"]["response_tokens"]
    hedged_tokens = member_stats["hedged"]["token_stats"]["response_tokens"]
    mean_tokens = (confident_tokens + hedged_tokens) / 2
    token_gap = abs(confident_tokens - hedged_tokens)
    token_gap_limit = max(
        config.pair_gap_min_tokens,
        math.ceil(config.pair_gap_mean_fraction * mean_tokens),
    )
    if token_gap > token_gap_limit:
        issues.append("pair_token_gap_over_dynamic_limit")
    if v3._normalized_text(confident) == v3._normalized_text(hedged):
        issues.append("pair_members_identical")
    edits = v3._edit_stats(source, confident, hedged)
    if edits["replacement_or_deletion_tokens"] == 0:
        issues.append("pair_insertion_only_difference")
    confident_words = _word_count(confident)
    hedged_words = _word_count(hedged)
    _, _, prompt_word_gap_limit = _prompt_word_targets(str(source["original_response"]))
    minimum_tokens = min(confident_tokens, hedged_tokens)
    token_ratio = max(confident_tokens, hedged_tokens) / max(1, minimum_tokens)
    return sorted(set(issues)), {
        "confident_response_tokens": confident_tokens,
        "hedged_response_tokens": hedged_tokens,
        "absolute_token_gap": token_gap,
        "dynamic_gap_limit": token_gap_limit,
        "max_min_token_ratio_diagnostic": token_ratio,
        "confident_word_count": confident_words,
        "hedged_word_count": hedged_words,
        "absolute_word_gap": abs(confident_words - hedged_words),
        "prompt_word_gap_target_max": prompt_word_gap_limit,
        "within_prompt_word_gap_target": (
            abs(confident_words - hedged_words) <= prompt_word_gap_limit
        ),
        "edit_stats": edits,
        "single_edit_region_diagnostic": edits["edit_regions"] < 2,
        "paragraph_block_difference_diagnostic": abs(
            member_stats["confident"]["paragraph_blocks"]
            - member_stats["hedged"]["paragraph_blocks"]
        ),
        "topology_and_scope_review": "pending_blind_semantic_audit",
    }


def validate_structured_output(
    batch: RewriteBatch,
    structured: dict[str, Any],
    config: RunnerConfig,
    tokenizer: Any,
) -> tuple[list[dict[str, Any]], list[str]]:
    received = structured.get("pairs", []) if isinstance(structured, dict) else []
    if not isinstance(received, list):
        received = []
    batch_issues: list[str] = []
    if len(received) != len(batch.rows):
        batch_issues.append("output_count_mismatch")
    if len(received) > len(batch.rows):
        batch_issues.append("unexpected_extra_records")
    records: list[dict[str, Any]] = []
    for index, source in enumerate(batch.rows):
        item = received[index] if index < len(received) and isinstance(received[index], dict) else {}
        issues: list[str] = []
        if item.get("source_id") != source["source_id"]:
            issues.append("source_id_or_order_mismatch")
        if item.get("original_response_sha256") != source["original_response_sha256"]:
            issues.append("source_hash_mismatch")
        if item.get("rewrite_recipe") != source["rewrite_recipe"]:
            issues.append("recipe_mismatch")
        if item.get("stance_topology") != source["stance_topology"]:
            issues.append("topology_mismatch")
        expected_labels = (
            ("confident", "hedged")
            if source["rewrite_output_order"] == "confident_first"
            else ("hedged", "confident")
        )
        if (item.get("first_label"), item.get("second_label")) != expected_labels:
            issues.append("label_or_output_order_mismatch")
        first = item.get("first_response", "")
        second = item.get("second_response", "")
        if not isinstance(first, str) or not isinstance(second, str):
            issues.append("response_not_string")
            first = first if isinstance(first, str) else ""
            second = second if isinstance(second, str) else ""
        confident = first if expected_labels[0] == "confident" else second
        hedged = second if expected_labels[1] == "hedged" else first
        writer_issues = item.get("issues", [])
        if not isinstance(writer_issues, list) or not all(isinstance(x, str) for x in writer_issues):
            issues.append("writer_issues_not_string_array")
            writer_issues = []
        not_applicable = item.get("not_applicable")
        member_stats: dict[str, dict[str, Any]] = {}
        pair_stats: dict[str, Any] = {}
        if not isinstance(not_applicable, bool):
            issues.append("not_applicable_not_boolean")
        if not_applicable is True:
            if first or second:
                issues.append("not_applicable_responses_not_empty")
            if not writer_issues:
                issues.append("not_applicable_missing_reason")
            status = "not_applicable" if not issues else "validation_failed"
        else:
            if not confident.strip() or not hedged.strip():
                issues.append("empty_response")
            if confident.strip() and hedged.strip():
                for label, response in (("confident", confident), ("hedged", hedged)):
                    member_validation, stats = member_issues(source, response, config, tokenizer)
                    issues.extend(f"{label}:{issue}" for issue in member_validation)
                    member_stats[label] = stats
                pair_validation, pair_stats = _pair_issues(
                    source, confident, hedged, config, member_stats
                )
                issues.extend(pair_validation)
            if writer_issues:
                issues.append("writer_reported_issue")
            status = (
                "accepted" if not issues
                else "needs_review" if set(issues) == {"writer_reported_issue"}
                else "validation_failed"
            )
        records.append({
            "source_id": source["source_id"],
            "original_response_sha256": source["original_response_sha256"],
            "source_suitability_status": source["source_suitability_status"],
            "rewrite_dev_set": batch.phase,
            "rewrite_recipe": source["rewrite_recipe"],
            "stance_topology": source["stance_topology"],
            "rewrite_output_order": source["rewrite_output_order"],
            "confident_response": confident,
            "hedged_response": hedged,
            "status": status,
            "validation_issues": sorted(set(issues)),
            "writer_issues": writer_issues,
            "member_stats": member_stats,
            "pair_stats": pair_stats,
            "human_review": "pending",
            "semantic_review_scope": [
                "content_and_scope_equivalence",
                "certainty_ordering",
                "topology_is_only_intended_contrast",
                "naturalness_and_batch_diversity",
                "no_new_example_generalization_or_elaboration",
            ],
        })
    batch_issues = sorted(set(batch_issues))
    if batch_issues:
        for record in records:
            record["validation_issues"] = sorted(set(
                record["validation_issues"] + [f"batch:{issue}" for issue in batch_issues]
            ))
            record["status"] = "validation_failed"
    return records, batch_issues


