"""Prepare the next single illustration batch, retaining previous attempts."""
import argparse
import copy
import hashlib
import json
import random
import re
from collections import Counter
from pathlib import Path

import build_factual_rewrite_review as review
from prepare_epistemic_preview import render_preview


BASE = Path(__file__).resolve().parents[1]
ROOT = BASE / "private_data" / "rewrite_canary_v1"
OUTPUT = ROOT / "economical_rewrite_v3"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render():
    sources = json.loads((OUTPUT / "SOURCE_ONLY.json").read_text())["sources"]
    manifest = json.loads((OUTPUT / "FLUENCY_INPUT_MANIFEST.json").read_text())
    if digest(OUTPUT / "WRITER_PROMPT_FLUENCY.txt") != manifest["writer_prompt_sha256"]:
        raise ValueError("saved fluency prompt changed")
    if digest(OUTPUT / "DRAFT_PAIRS.json") != manifest["raw_initial_draft_sha256"]:
        raise ValueError("initial draft changed")
    raw = OUTPUT / "DRAFT_PAIRS_FLUENCY.json"
    drafts = copy.deepcopy(json.loads(raw.read_text())["pairs"])
    by_id = {row["preview_id"]: row for row in drafts}
    if len(drafts) != 3 or len(by_id) != 3 or set(by_id) != {row["preview_id"] for row in sources}:
        raise ValueError("drafts must cover the same three source IDs")
    patch_path = OUTPUT / "EDITORIAL_CLARIFICATIONS.json"
    changes = json.loads(patch_path.read_text())["changes"]
    for change in changes:
        text = by_id[change["preview_id"]][change["field"]]
        if text.count(change["before"]) != 1:
            raise ValueError("editorial clarification no longer matches exactly")
        by_id[change["preview_id"]][change["field"]] = text.replace(change["before"], change["after"], 1)
    review._write_json(OUTPUT / "REVIEW_PAIRS.json", {"pairs": drafts})
    a_roles = ["confident", "hesitant", "confident"]
    random.Random(20261018).shuffle(a_roles)
    cards, key, counts = [], [], []
    for source, role_a in zip(sources, a_roles):
        identifier = source["preview_id"]
        pair = by_id[identifier]
        role_b = "hesitant" if role_a == "confident" else "confident"
        cards.append({"review_id": identifier, "question": source["prompt"],
                      "original_response": source["original_response"],
                      "version_a": pair[role_a + "_response"], "version_b": pair[role_b + "_response"]})
        key.append({"preview_id": identifier, "version_a_role": role_a})
        number_set = Counter(re.findall(r"\b\d+(?:[.,]\d+)*\b", source["original_response"]))
        lengths = {}
        for role in ("confident", "hesitant"):
            text = pair[role + "_response"]
            if not text.strip() or Counter(re.findall(r"\b\d+(?:[.,]\d+)*\b", text)) != number_set:
                raise ValueError("missing response or numeric detail discrepancy")
            if re.search(r"\b(?:seem|seems|appear|appears|I)\b", text):
                raise ValueError("unexpected new hedge or first-person word in these three examples")
            lengths[role] = len(text.split())
        counts.append(lengths)
    packet_hash = review.sha256_value(cards)
    page = OUTPUT / "reviewer_only" / "BLIND_REVIEW.html"
    page.parent.mkdir(exist_ok=True)
    page.write_text(render_preview(cards, packet_hash,
        title="Three Luna prompt examples",
        intro="Three development illustrations generated by GPT-6 Luna at medium effort. Two technical-scope phrases in the scientific example were clarified by the parent session; raw drafts are preserved. WordNet substitution and length quotas were not used. Researcher review is pending.",
        export_name="rewrite_v3_examples_feedback.json", feedback_schema="rewrite-v3-examples-feedback-v1"), encoding="utf-8")
    (OUTPUT / "private_key").mkdir(exist_ok=True)
    review._write_json(OUTPUT / "private_key" / "KEY.json", {"packet_sha256": packet_hash, "rows": key})
    status = {"schema": "rewrite-illustrations-v3-status-v1", "source_count": 3,
              "status": "illustrations_pending_researcher_review", "writer_model": "gpt-6-luna",
              "reasoning_effort": "medium", "writer_contexts_this_step": 2,
              "editorial_clarification_count": len(changes), "raw_outputs_preserved": True,
              "wordnet_used": False, "length_quotas_used": False,
              "length_measure": "whitespace_words_not_model_tokens", "word_counts": counts,
              "human_review_certified": False, "independent_blind_review_completed": False,
              "probe_fitting_started": False, "activation_extraction_started": False,
              "sdt_training_started": False, "packet_sha256": packet_hash,
              "input_sha256": {"source": digest(OUTPUT / "SOURCE_ONLY.json"),
                               "writer_prompt": digest(OUTPUT / "WRITER_PROMPT_FLUENCY.txt"),
                               "raw_draft": digest(raw), "editorial_clarifications": digest(patch_path),
                               "review_pairs": digest(OUTPUT / "REVIEW_PAIRS.json")},
              "interpretation": "Development examples only. Medium effort, prompts and constraints changed together; no causal claim about the reason for any quality difference. Length and vocabulary confounds still require later controls."}
    review._write_json(BASE / "results" / "rewrite_illustrations_v3_status.json", status)
    print(json.dumps({"source_count": 3, "writer_model": "gpt-6-luna", "reasoning_effort": "medium",
                      "editorial_clarifications": len(changes), "word_counts": counts}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--render", action="store_true")
    args = parser.parse_args()
    if args.render:
        render()
        return
    old_source = ROOT / "wordnet_luna_preview_v2" / "SOURCE_ONLY.json"
    source_rows = json.loads(old_source.read_text(encoding="utf-8"))["sources"]
    rows = [{field: row[field] for field in ("preview_id", "prompt", "original_response")}
            for row in source_rows]
    if len(rows) != 3:
        raise ValueError("expected the same three sources")
    if (OUTPUT / "DRAFT_PAIRS.json").exists():
        raise FileExistsError("saved drafts exist; do not regenerate")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    source_text = json.dumps({"sources": rows}, ensure_ascii=False, separators=(",", ":"))
    prompt = BASE / "prompts" / "economical_rewrite_v3.txt"
    config = BASE / "configs" / "economical_rewrite_v3.json"
    (OUTPUT / "SOURCE_ONLY.json").write_text(source_text + "\n", encoding="utf-8")
    (OUTPUT / "WRITER_PROMPT.txt").write_text(prompt.read_text(encoding="utf-8") + "\nINPUT_JSON\n" + source_text + "\n", encoding="utf-8")
    manifest = {"schema": "economical-rewrite-v3-input-v1", "source_count": 3,
                "writer_model": "gpt-6-luna", "reasoning_effort": "medium",
                "input_sha256": {"source": digest(OUTPUT / "SOURCE_ONLY.json"),
                                 "writer_prompt": digest(OUTPUT / "WRITER_PROMPT.txt"),
                                 "config": digest(config), "prompt_template": digest(prompt)},
                "previous_attempts_preserved": True, "model_calls_made_by_preparation": 0}
    (OUTPUT / "INPUT_MANIFEST_PRIVATE.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"source_count": 3, "writer_model": "gpt-6-luna",
                      "reasoning_effort": "medium", "writer_prompt_characters": len((OUTPUT / "WRITER_PROMPT.txt").read_text())}))


if __name__ == "__main__":
    main()
